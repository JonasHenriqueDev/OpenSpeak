/**
 * Tradução com interpolação {param} e plural "a | b | c" via params.count/n.
 */
export function t(key, params = {}) {
  let s = STRINGS[key] ?? key;
  if (s.includes(' | ')) {
    const forms = s.split(' | ');
    const n = Number(params.count ?? params.n ?? 0);
    s = forms.length === 3 ? forms[Math.min(n, 2)] : forms[n === 1 ? 0 : 1];
  }
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}
